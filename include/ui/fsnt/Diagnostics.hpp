#pragma once

#include <QList>
#include <QString>

#include <functional>

namespace Fsnt {
    // Самопроверка клиента.
    //
    // Состояние «подключено, но ничего не работает» имеет с десяток причин, и
    // почти ни одну из них пользователь не может увидеть: чужой сетевой фильтр,
    // не включённый системный прокси, удалённое антивирусом ядро, сбитые часы.
    // Разбирать их по одной вручную — это часы переписки с поддержкой на каждый
    // случай, поэтому клиент проверяет себя сам и говорит, что именно чинить.
    struct CheckResult {
        enum State {
            Ok,       // всё в порядке
            Warning,  // работает, но может мешать
            Failed,   // сломано
            Skipped,  // к текущей конфигурации не относится
        };

        State state = Ok;
        QString detail;    // что именно не так, человеческим языком
        QString fixLabel;  // подпись кнопки; пусто — чинить нечем
        // Выполняется в потоке интерфейса: может показывать диалоги.
        std::function<void()> fix;
    };

    struct Check {
        QString title;
        // Выполняется в рабочем потоке: часть проверок ходит в сеть и запускает
        // внешние программы, и держать на этом интерфейс нельзя.
        std::function<CheckResult()> run;
    };

    // Порядок важен: проверки идут от причины к следствию, чтобы первая красная
    // строка и была настоящей поломкой, а не её последствием.
    QList<Check> BuildChecks();
} // namespace Fsnt
