#pragma once

class QWidget;

namespace Fsnt {
    // Системная рамка окна — заголовок с кнопками — принадлежит не нам, а
    // оконному менеджеру, и о теме приложения он знать не обязан. На Windows
    // светлая полоса над тёмным окном выглядела чужеродно, и красить её надо
    // отдельным вызовом.
    //
    // Вне Windows всё это пусто: macOS и Linux подхватывают тему сами.

    // Одно окно. Безопасно вызывать до показа: рамка обновится при отрисовке.
    void ApplyWindowChrome(QWidget *window);

    // Все открытые окна приложения — после смены темы.
    void RefreshWindowChrome();

    // Ставит наблюдателя, который красит каждое новое окно при показе и все окна
    // при смене темы. Вызывается один раз при запуске.
    void InstallWindowChromeWatcher();
} // namespace Fsnt
