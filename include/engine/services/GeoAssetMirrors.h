#pragma once

#include <QString>
#include <QStringList>

namespace Engine {
    // Запасные источники для geoip.dat и geosite.dat.
    //
    // Файлы лежат на GitHub, а он у части пользователей то режется, то отдаёт
    // обрыв на середине. Одного адреса мало: без geosite.dat не собирается
    // конфиг, и человек видит отказ подключения, причина которого к VPN
    // отношения не имеет.
    //
    // Зеркала — это тот же самый репозиторий, доставленный другим путём, а не
    // другой набор правил. Разные наборы называют категории по-своему
    // (category-ads-all есть не везде), и подмена источника тихо меняет смысл
    // правил маршрутизации: конфиг соберётся, а ядро откажется его принять,
    // сославшись на отсутствующую категорию. Выбор другого набора — осознанное
    // действие человека в настройках, а не запасной путь при сбое сети.
    //
    // Первым всегда идёт заданный адрес: если он работает, ничего не меняется.
    // Адреса не с GitHub возвращаются как есть — зеркалить их нечем.
    QStringList GeoAssetMirrors(const QString &url);
} // namespace Engine
