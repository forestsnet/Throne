#pragma once

#include <QMap>
#include <QString>
#include <QStringList>

namespace Configs {
    // Адреса сервера профиля, добытые до того, как поднялся туннель.
    //
    // Имя своего же сервера нужно каждому новому соединению, а не только
    // первому, и разрешать его под туннелем не на чем: обычный 53-й порт
    // закрывает фильтр строгой маршрутизации, имя шифрованного резолвера
    // разрешать нечем, а DoT и DoH в сети человека может не оказаться вовсе.
    // Зато пока туннеля нет, работает всё — и подбор прямого DNS всё равно
    // спрашивает именно это имя, чтобы проверить резолвер. Ответ оттуда и
    // кладётся сюда, а сборщик конфига отдаёт его ядру готовым.
    //
    // Только в памяти и только на время сессии: подписка переезжает, и
    // записанный адрес завтра соврёт. Каждое подключение спрашивает заново.
    void SetServerAddressPin(const QString &domain, const QStringList &addresses);

    void ClearServerAddressPins();

    QMap<QString, QStringList> ServerAddressPins();
}
