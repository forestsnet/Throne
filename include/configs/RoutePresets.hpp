#pragma once

#include <QList>
#include <QString>

namespace Configs {
    // Готовая маршрутизация под понятный сценарий.
    //
    // Редактор маршрутов — это конструктор правил: тип совпадения, набор
    // адресов, исходящий тег. Собрать в нём разумную схему может тот, кто уже
    // знает, как устроена маршрутизация, а остальным нужен ответ на вопрос
    // «что выбрать», а не поле для ввода.
    struct RoutePreset {
        QString key;          // стабилен, хранится в имени профиля
        QString title;        // переведённое имя для простого режима
        QString description;  // одна строка: что это значит на практике
    };

    QList<RoutePreset> RoutePresets();

    // Имя профиля в базе. Не переводится: по нему мы узнаём свой профиль среди
    // пользовательских, и смена языка не должна создавать второй такой же.
    QString RoutePresetProfileName(const QString &key);

    // Ключ пресета, если профиль создан нами; иначе пустая строка.
    QString RoutePresetKeyOf(const QString &profileName);

    // Нетронутый стоковый профиль Default по смыслу и есть «всё через VPN», но
    // называется так, что новичку ничего не говорит. Показываем его как пресет,
    // а сам профиль не трогаем: пользователь мог его отредактировать, и правила
    // из-под него уводить нельзя.
    bool IsUntouchedDefaultProfile(int profileId);

    // Возвращает id профиля пресета, создавая его при необходимости.
    // Существующий пересобирается: правила пресета задаём мы, и исправления в
    // них должны доезжать до тех, кто выбрал пресет раньше.
    int EnsureRoutePreset(const QString &key);
} // namespace Configs
