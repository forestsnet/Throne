#pragma once

#include <QList>
#include <QString>

namespace Configs {
    struct SuccessorCandidate {
        int id = -1;
        QString name;
        QString type;
    };

    // Имя сервера в подписке обрастает пометками: флаг, эмодзи, скорость в
    // скобках. Сравнение один в один на них и спотыкается — «Финляндия
    // [25 Gbps]» и «Финляндия [20 Gbps]» для него разные серверы, хотя для
    // человека это один и тот же. Оставляем только буквы и цифры в нижнем
    // регистре: скобки уходят вместе с содержимым, а эмодзи и флаги не проходят
    // проверку на букву, потому что состоят из суррогатных пар.
    QString ComparableProfileName(const QString &name);

    // Замена профилю, который обновление подписки унесло из группы: сначала
    // точное совпадение имени, потом имя без пометок, и только если ни то ни
    // другое не дало ровно одного — первый в списке. Имена сравниваем лишь
    // внутри своего типа: рядом стоит резерв с тем же названием и другим
    // транспортом, и подставлять его вместо основного не за что. Возвращает -1
    // на пустом списке.
    int PickSuccessor(const QString &name, const QString &type, const QList<SuccessorCandidate> &candidates);
}
