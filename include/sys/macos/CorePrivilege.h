#pragma once

#include <QString>

// Право ядра на туннель — не на один запуск, а на всю установку.
//
// setuid принадлежит файлу, а не пути: обновление кладёт новый файл ядра, и
// право уходит вместе со старым. Поэтому каждое обновление заканчивалось
// запросом пароля, а автоматическое — молча оборванным VPN: окно всплывало
// тогда, когда человека нет за машиной, и до него никто не доходил.
//
// Переносить ядро в другой каталог бессмысленно по той же причине. Поэтому
// ставим системную службу: launchd следит за файлом ядра и возвращает ему
// root:wheel и setuid, как только файл меняется. launchd работает от root
// независимо от того, кому принадлежит файл, так что пароль нужен один раз —
// на установку самой службы.
//
// Цена, которую надо называть прямо: пока служба стоит, тот, кто может писать
// в бандл приложения, получает root без пароля. Это та же сделка, на которую
// идёт любой клиент с привилегированным помощником, и ровно её человек
// подтверждает тем самым паролем. Поэтому служба ставится только по явному
// согласию и снимается там же, где выдавалась.
namespace Sys::MacCorePrivilege {
    // Стоит ли служба и следит ли она именно за этим файлом ядра. Если
    // приложение переехало, ответ «нет»: следующая выдача переставит службу.
    bool WatchesCore(const QString &corePath);

    // Стоит ли служба вообще, пусть и за другим файлом.
    bool Installed();

    // Одна авторизация на всё: ставит службу и сразу выдаёт право текущему
    // ядру, не дожидаясь, пока служба заметит файл. В code — код возврата
    // osascript, kMacAuthCancelled означает закрытое окно пароля.
    bool Install(const QString &corePath, const QString &prompt, int *code = nullptr);

    // Снимает службу и забирает setuid у ядра.
    bool Remove(const QString &corePath, const QString &prompt, int *code = nullptr);
} // namespace Sys::MacCorePrivilege
